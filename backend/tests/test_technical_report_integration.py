def test_3_draft_preview_generation():
    """Verify draft preview returns PDF stream and does not write to report_records table."""
    db = SessionLocal()
    try:
        ce_user, _, _, case_1, _, _ = get_or_create_test_entities(db)

        initial_count = db.query(ReportRecord).filter(ReportRecord.case_id == str(case_1.id)).count()

        req = ReportRequest(
            case_id=str(case_1.id),
            report_type=ReportType.COMPREHENSIVE,
            conclusions_text="Preliminary automated test conclusion"
        )
        resp = preview_report(case_1.id, report=req, db=db, current_user=ce_user)
        assert hasattr(resp, "path")
        assert Path(resp.path).exists()

        # Database record count must NOT have increased!
        after_count = db.query(ReportRecord).filter(ReportRecord.case_id == str(case_1.id)).count()
        assert after_count == initial_count
    finally:
        db.close()
    print("PASS: test_3_draft_preview_generation")


def test_4_final_report_generation():
    """Verify final report generation creates ReportRecord and audit logs."""
    db = SessionLocal()
    try:
        ce_user, _, _, case_1, _, ev_1 = get_or_create_test_entities(db)

        req = ReportRequest(
            case_id=str(case_1.id),
            report_type=ReportType.COMPREHENSIVE,
            conclusions_text="Formal forensic conclusion: Evidence verified and authentic.",
            recommendations_text="Store image safely."
        )
        res = generate_report(case_1.id, payload=req, db=db, current_user=ce_user)

        res_status = res["status"] if isinstance(res, dict) else res.status
        res_draft = res["is_draft"] if isinstance(res, dict) else res.is_draft
        res_rep_id = res["report_id"] if isinstance(res, dict) else res.report_id
        res_fname = res["file_name"] if isinstance(res, dict) else res.file_name
        res_dl = res["download_url"] if isinstance(res, dict) else res.download_url
        res_prev = res["preview_url"] if isinstance(res, dict) else res.preview_url

        assert res_status == "success"
        assert res_draft is False
        assert res_rep_id is not None
        assert res_fname.endswith(".pdf")
        assert res_dl is not None
        assert res_prev is not None

        # Verify persisted in report_records
        rec = db.query(ReportRecord).filter(ReportRecord.id == res_rep_id).first()
        assert rec is not None
        assert rec.case_id == str(case_1.id)
        assert rec.investigator_name == (ce_user.full_name or ce_user.username)
        assert rec.file_size_bytes > 1000

        # Verify audit trail entries
        c_entry = db.query(CustodyLog).filter(
            CustodyLog.related_reference == res_rep_id
        ).first()
        assert c_entry is not None
        assert c_entry.action == "REPORT_GENERATED"

        a_entry = db.query(ActivityLog).filter(
            ActivityLog.action == "REPORT_GENERATED",
            ActivityLog.case_id == str(case_1.id)
        ).first()
        assert a_entry is not None
    finally:
        db.close()
    print("PASS: test_4_final_report_generation")


