def test_7_cross_case_isolation():
    """Verify reports from Case 1 cannot be accessed via Case 2 endpoint."""
    db = SessionLocal()
    try:
        ce_user, other_ce, _, case_1, case_2, _ = get_or_create_test_entities(db)

        rec_case_1 = db.query(ReportRecord).filter(ReportRecord.case_id == str(case_1.id)).first()
        assert rec_case_1 is not None

        # Trying to access Case 1 report via Case 2 endpoint -> 404
        try:
            download_report_by_id(case_2.id, report_id=rec_case_1.id, db=db, current_user=other_ce)
            assert False, "Expected 404 cross-case rejection"
        except HTTPException as e:
            assert e.status_code == 404
            assert "does not belong" in str(e.detail).lower()

        # Non-existent report -> 404
        try:
            download_report_by_id(case_1.id, report_id="non-existent-rep-999", db=db, current_user=ce_user)
            assert False, "Expected 404 for missing report"
        except HTTPException as e:
            assert e.status_code == 404
    finally:
        db.close()
    print("PASS: test_7_cross_case_isolation")


