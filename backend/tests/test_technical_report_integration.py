def test_1_authorization_and_scoping():
    """Verify role_id == 3 and assigned case scoping."""
    db = SessionLocal()
    try:
        ce_user, other_ce, inv_user, case_1, case_2, _ = get_or_create_test_entities(db)

        # 1. Unauthenticated -> 401
        try:
            verify_cyber_expert_case_access(case_1.id, None, db)
            assert False, "Expected 401"
        except HTTPException as e:
            assert e.status_code == 401

        # 2. Non-Expert (role_id=2) -> 403
        try:
            verify_cyber_expert_case_access(case_1.id, inv_user, db)
            assert False, "Expected 403"
        except HTTPException as e:
            assert e.status_code == 403

        # 3. Non-existent Case -> 404
        try:
            verify_cyber_expert_case_access(99999999, ce_user, db)
            assert False, "Expected 404"
        except HTTPException as e:
            assert e.status_code == 404

        # 4. Unassigned Case -> 403
        try:
            verify_cyber_expert_case_access(case_2.id, ce_user, db)
            assert False, "Expected 403"
        except HTTPException as e:
            assert e.status_code == 403
            assert "not assigned" in str(e.detail).lower()

        # 5. Assigned Expert -> 200 (Success)
        verified_case = verify_cyber_expert_case_access(case_1.id, ce_user, db)
        assert verified_case.id == case_1.id
    finally:
        db.close()
    print("PASS: test_1_authorization_and_scoping")


